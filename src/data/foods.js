// 공백/대소문자 무시 검색. 이름 시작 일치 → 이름 포함 → 별칭/분류 순으로 정렬.
// extra 에는 AI로 찾아 저장해 둔 사용자 음식이 들어온다(먼저 노출).
export function searchFoods(query, limit = 8, extra = []) {
  const q = query.trim().toLowerCase().replace(/\s+/g, '')
  if (!q) return []
  const scored = []
  for (const f of [...extra, ...FOODS]) {
    const name = f.n.toLowerCase().replace(/\s+/g, '')
    let score = -1
    if (name.startsWith(q)) score = 0
    else if (name.includes(q)) score = 1
    else if ((f.a || []).some((al) => al.toLowerCase().includes(q))) score = 2
    else if ((f.c || '').toLowerCase().includes(q)) score = 3
    if (score >= 0) scored.push({ f, score: f.ai ? score - 0.5 : score })
  }
  const seen = new Set()
  return scored
    .sort((a, b) => a.score - b.score || a.f.n.length - b.f.n.length)
    .filter((s) => (seen.has(s.f.n) ? false : seen.add(s.f.n)))
    .slice(0, limit)
    .map((s) => s.f)
}
